// Writes the gitignored env files for localhost. Safe to re-run; refuses to overwrite unless --force.
//
// Both files are full TESTNET profiles (the testnet pipeline updates `.env.testnet`, `.env` and
// `apps/web/.env` together and requires all three to pass the same guards: mode 0600, TESTNET,
// execution flags off, a parseable PROTOCOL_ADDRESSES). They start with a schema-valid placeholder
// deployment; the real token map is taken from `.env.testnet` when it exists.
import fs from "node:fs";
import path from "node:path";
import { ROOT, SUPABASE_URL, readEnvFile, signJwt } from "./lib.mjs";

const force = process.argv.includes("--force");
const stub = (n) => "0x" + n.toString(16).padStart(40, "0");

function write(file, entries, header) {
  if (fs.existsSync(file) && !force) {
    console.log(`  keep   ${path.relative(ROOT, file)} (use --force to rewrite)`);
    return;
  }
  fs.writeFileSync(file, [`# ${header}`, ...entries.map(([k, v]) => `${k}=${v}`), ""].join("\n"));
  fs.chmodSync(file, 0o600); // writeFileSync's mode only applies to new files
  console.log(`  wrote  ${path.relative(ROOT, file)}`);
}

// Public token map from the testnet profile, when one exists (addresses only, no secrets).
function knownTokens() {
  const profile = path.join(ROOT, ".env.testnet");
  if (!fs.existsSync(profile)) return null;
  const raw = new Map(readEnvFile(profile)).get("PROTOCOL_ADDRESSES");
  try {
    const parsed = JSON.parse(raw.replace(/^'|'$/g, ""));
    return parsed?.tokens?.USDG ? parsed.tokens : null;
  } catch {
    return null;
  }
}

const tokens = knownTokens() ?? { USDG: stub(0xa0) };
const usdg = tokens.USDG;
const shared = new Map(readEnvFile(path.join(ROOT, ".env.testnet.example")));
const overrides = {
  RPC_URL: "https://rpc.testnet.chain.robinhood.com",
  BACKEND_API_URL: "http://localhost:3001",
  USDG_ADDRESS: usdg,
  PROTOCOL_ADDRESSES: `'${JSON.stringify({
    usdg,
    oracle: stub(0xa1),
    registry: stub(0xa2),
    nashRouter: stub(0xa3),
    leverageRouter: stub(0xa4),
    shortRouter: stub(0xa5),
    autoProtect: stub(0xa6),
    nashVault: stub(0xa7),
    tokens,
    pairs: {},
  })}'`,
  MARKET_DEPLOYMENTS_JSON: "'[]'",
  SUPABASE_URL,
  SUPABASE_ANON_KEY: signJwt("anon"),
  PRIVATE_KEY: "",
  KEEPER_PRIVATE_KEY: "",
  DATABASE_URL: "",
  SUPABASE_SERVICE_ROLE_KEY: "",
};
for (const [k, v] of Object.entries(overrides)) shared.set(k, v);

// Web: public configuration only, never a service-role key.
write(
  path.join(ROOT, "apps/web/.env"),
  [...shared.entries()],
  "Generated by `pnpm localnet:up`. Placeholder deployment, no secrets. Real addresses arrive from the testnet pipeline.",
);

// Repo root: same profile plus the local service-role key the API uses for writes.
const root = new Map(shared);
root.set("SUPABASE_SERVICE_ROLE_KEY", signJwt("service_role"));
write(
  path.join(ROOT, ".env"),
  [...root.entries()],
  "Generated by `pnpm localnet:up`. Local-only credentials; never commit.",
);
