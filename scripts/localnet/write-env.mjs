// Writes the gitignored env files for localhost. Safe to re-run; refuses to overwrite unless --force.
import fs from "node:fs";
import path from "node:path";
import { ROOT, SUPABASE_URL, readEnvFile, signJwt } from "./lib.mjs";

const force = process.argv.includes("--force");
const stub = (n) => "0x" + n.toString(16).padStart(40, "0");

function write(file, rows, header) {
  if (fs.existsSync(file) && !force) {
    console.log(`  keep   ${path.relative(ROOT, file)} (use --force to rewrite)`);
    return;
  }
  fs.writeFileSync(file, [`# ${header}`, ...rows.map(([k, v]) => `${k}=${v}`), ""].join("\n"), { mode: 0o600 });
  console.log(`  wrote  ${path.relative(ROOT, file)}`);
}

// API: reads SUPABASE_* and a few switches from the repo-root .env.
write(
  path.join(ROOT, ".env"),
  [
    ["PORT", "3001"],
    ["NODE_ENV", "development"],
    ["API_BIND_HOST", "127.0.0.1"],
    ["WEB_ORIGIN", "http://localhost:3002"],
    ["NETWORK_MODE", "TESTNET"],
    ["TRADING_ENABLED", "false"],
    ["SUPABASE_URL", SUPABASE_URL],
    ["SUPABASE_ANON_KEY", signJwt("anon")],
    ["SUPABASE_SERVICE_ROLE_KEY", signJwt("service_role")],
  ],
  "Generated by `pnpm localnet:up`. Local-only credentials; never commit.",
);

// Web: start from the committed testnet template, then pin a schema-valid placeholder deployment.
// Lending/margin/trading stay disabled until real Nash contracts are deployed (see docs/TESTNET.md).
const web = new Map(readEnvFile(path.join(ROOT, ".env.testnet.example")));
const usdg = stub(0xa0);
const overrides = {
  RPC_URL: "https://rpc.testnet.chain.robinhood.com",
  BACKEND_API_URL: "http://localhost:3001",
  USDG_ADDRESS: usdg,
  PROTOCOL_ADDRESSES: `'${JSON.stringify({
    usdg,
    oracle: stub(0xa1),
    registry: stub(0xa2),
    nashRouter: stub(0xa3),
    leverageRouter: stub(0xa4),
    shortRouter: stub(0xa5),
    autoProtect: stub(0xa6),
    nashVault: stub(0xa7),
    tokens: { USDG: usdg },
    pairs: {},
  })}'`,
  MARKET_DEPLOYMENTS_JSON: "'[]'",
  // The web's Pons routes read Supabase REST directly (server-side, anon key only).
  SUPABASE_URL: SUPABASE_URL,
  SUPABASE_ANON_KEY: signJwt("anon"),
  PRIVATE_KEY: "",
  KEEPER_PRIVATE_KEY: "",
  DATABASE_URL: "",
  SUPABASE_SERVICE_ROLE_KEY: "",
};
for (const [k, v] of Object.entries(overrides)) web.set(k, v);
write(
  path.join(ROOT, "apps/web/.env"),
  [...web.entries()],
  "Generated by `pnpm localnet:up`. Placeholder deployment, no secrets. Replace with real addresses after a testnet deploy.",
);
