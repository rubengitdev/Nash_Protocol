#!/usr/bin/env node
// Typesets the hero's formulas with KaTeX (Computer Modern, the face of mathematics journals) at build
// time, so the browser receives static HTML and no KaTeX code.
//   node scripts/render-formulas.mjs
// Output: apps/web/src/components/nash/formulas.generated.ts (committed; rerun after editing this list).
//
// Every formula is tied to a source:
//   nash-equilibrium  Nash, "Equilibrium points in n-person games", PNAS 36(1), 1950
//   fixed-point       the same paper: an equilibrium is a fixed point of the best-response correspondence
//   bargaining        Nash, "The Bargaining Problem", Econometrica 18(2), 1950
//   cipher            Nash's 1955 letters to the NSA contrast the attacker's effort: "a relatively small power of"
//                     the key length for weak ciphers versus exponential for strong ones. Nothing is claimed
//                     about the legitimate user's effort, which the letters do not state.
//   pow               Nakamoto 2008 section 4: a hash that "begins with a number of zero bits"
//   catch-up          Nakamoto 2008 section 11: the attacker's catch-up probability q_z
//   health, ltv       Nash Protocol: health factor and loan-to-value
//   amm               the margin pool is a Uniswap V2 pair: constant product x * y = k
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "apps/web/package.json"));
const katex = require("katex");

const FORMULAS = [
  {
    id: "nash-equilibrium",
    latex: String.raw`\forall i:\quad u_i\!\left(s_i^{*},\,s_{-i}^{*}\right)\;\ge\;u_i\!\left(s_i,\,s_{-i}^{*}\right)`,
  },
  { id: "fixed-point", latex: String.raw`\sigma^{*}\in\mathrm{BR}\!\left(\sigma^{*}\right)` },
  { id: "bargaining", latex: String.raw`\max_{x\in S}\;\bigl(u_1(x)-d_1\bigr)\bigl(u_2(x)-d_2\bigr)` },
  { id: "cipher", latex: String.raw`T_{\mathrm{attack}}(n):\quad n^{c}\;\ll\;e^{\,n}` },
  { id: "pow", latex: String.raw`\mathrm{SHA256}^{2}(h)\;<\;2^{\,256-k}` },
  {
    id: "catch-up",
    latex: String.raw`q_z=\begin{cases}1 & p\le q\\[4pt]\left(\dfrac{q}{p}\right)^{\!z} & p>q\end{cases}`,
  },
  { id: "health", latex: String.raw`\mathrm{HF}=\dfrac{C\cdot\mathrm{LLTV}}{D}\;>\;1` },
  { id: "ltv", latex: String.raw`\mathrm{LTV}=\dfrac{D}{C}\;\le\;\mathrm{LLTV}` },
  { id: "amm", latex: String.raw`x\cdot y=k` },
];

const out = {};
for (const { id, latex } of FORMULAS) {
  out[id] = katex.renderToString(latex, { displayMode: false, output: "html", throwOnError: true, strict: "error" });
}

const file = path.join(root, "apps/web/src/components/nash/formulas.generated.ts");
fs.writeFileSync(
  file,
  `// GENERATED by scripts/render-formulas.mjs from KaTeX. Do not edit by hand.\n` +
    `export const FORMULA_HTML: Record<${FORMULAS.map((f) => JSON.stringify(f.id)).join(" | ")}, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${path.relative(root, file)}: ${FORMULAS.length} formulas, ${(fs.statSync(file).size / 1024).toFixed(1)} KB`);
